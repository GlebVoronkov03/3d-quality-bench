OMML_NS = "http://schemas.openxmlformats.org/officeDocument/2006/math"


def omml(inner: str):
    xml = (
        f'<m:oMath xmlns:m="{OMML_NS}" xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main">'
        f"{inner}</m:oMath>"
    )
    return parse_xml(xml)


def t(text: str, italic: bool = True) -> str:
    sty = "<m:rPr><m:sty m:val='i'/></m:rPr>" if italic else "<m:rPr><m:sty m:val='p'/></m:rPr>"
    return f"<m:r>{sty}<m:t xml:space='preserve'>{text}</m:t></m:r>"


def sub(base: str, idx: str, italic_base: bool = True) -> str:
    return (
        "<m:sSub><m:e>"
        + t(base, italic_base)
        + "</m:e><m:sub>"
        + t(idx, False)
        + "</m:sub></m:sSub>"
    )


def sup(base: str, idx: str) -> str:
    return (
        "<m:sSup><m:e>"
        + t(base)
        + "</m:e><m:sup>"
        + t(idx, False)
        + "</m:sup></m:sSup>"
    )


def frac(num: str, den: str) -> str:
    return f"<m:f><m:num>{num}</m:num><m:den>{den}</m:den></m:f>"


def nary_sum(body: str, sub_s: str, sup_s: str) -> str:
    return (
        "<m:nary><m:naryPr><m:chr m:val='∑'/></m:naryPr>"
        f"<m:sub>{sub_s}</m:sub><m:sup>{sup_s}</m:sup><m:e>{body}</m:e></m:nary>"
    )


def eq_p(doc: Document, inner: str) -> None:
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_before = Pt(8)
    p.paragraph_format.space_after = Pt(8)
    p._p.append(omml(inner))


def set_run_font(run, size=11, bold=False, italic=False) -> None:
    run.font.name = "Times New Roman"
    run._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic


def add_p(doc, text, size=11, bold=False, italic=False, first_line=True) -> None:
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(6)
    p.paragraph_format.line_spacing_rule = WD_LINE_SPACING.ONE_POINT_FIVE
    if first_line:
        p.paragraph_format.first_line_indent = Cm(1.25)
    r = p.add_run(text)
    set_run_font(r, size=size, bold=bold, italic=italic)


def add_h(doc, text, level=1) -> None:
    p = doc.add_heading(text, level=level)
    for run in p.runs:
        run.font.color.rgb = RGBColor(0x22, 0x22, 0x22)
        run.font.name = "Times New Roman"
        run._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")


def caption(doc, text: str) -> None:
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_after = Pt(12)
    p.paragraph_format.first_line_indent = Cm(0)
    r = p.add_run(text)
    set_run_font(r, size=10, italic=True)


def add_fig(doc, name: str, cap: str, width=16.0) -> None:
    path = DOCS / name
    if not path.exists():
        add_p(doc, f"[рисунок не найден: {name}]", italic=True, first_line=False)
        return
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.first_line_indent = Cm(0)
    run = p.add_run()
    run.add_picture(str(path), width=Cm(width))
    caption(doc, cap)


def shade_header(cell) -> None:
    tc = cell._tc
    tcPr = tc.get_or_add_tcPr()
    tcPr.append(parse_xml(r'<w:shd {} w:fill="1F3A5F" w:val="clear"/>'.format(nsdecls("w"))))
    for p in cell.paragraphs:
        for run in p.runs:
            run.font.color.rgb = RGBColor(255, 255, 255)
            run.bold = True
            run.font.size = Pt(8)
            run.font.name = "Times New Roman"


def fill_cell(cell, text, size=8, bold=False) -> None:
    cell.text = ""
    p = cell.paragraphs[0]
    p.paragraph_format.space_after = Pt(0)
    p.paragraph_format.space_before = Pt(0)
    r = p.add_run(str(text))
    set_run_font(r, size=size, bold=bold)


def add_table(doc, headers, rows, col_cm=None) -> None:
    table = doc.add_table(rows=1 + len(rows), cols=len(headers))
    table.style = "Table Grid"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    for j, h in enumerate(headers):
        fill_cell(table.rows[0].cells[j], h, size=8, bold=True)
        shade_header(table.rows[0].cells[j])
    for i, row in enumerate(rows, start=1):
        for j, val in enumerate(row):
            fill_cell(table.rows[i].cells[j], val, size=8)
    doc.add_paragraph()


def setup_doc() -> Document:
    doc = Document()
    sec = doc.sections[0]
    sec.page_width = Cm(21.0)
    sec.page_height = Cm(29.7)
    sec.left_margin = Cm(2.5)
    sec.right_margin = Cm(2.0)
    sec.top_margin = Cm(2.0)
    sec.bottom_margin = Cm(2.0)
    style = doc.styles["Normal"]
    style.font.name = "Times New Roman"
    style.font.size = Pt(11)
    style._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    return doc


